/**
 * 페르소나 prompt 에 박을 example 섹션 문자열 빌드.
 * 예시 0개면 빈 문자열 반환 (다른 페르소나 빈 상태 호환).
 */
export function buildExamplesSection(personaId) {
  const examples = PERSONA_EXAMPLES[personaId];
  if (!examples || examples.length === 0) return '';

  const lines = [
    '',
    '### [EXAMPLES] 캐릭터 톤 / 길이 / 행동서술 시연',
    '아래는 trigger 별 응답 예시. **표현 그대로 베끼지 마라 — 변주해라.**',
    '핵심은 (1) 상태별 톤 변화 (2) 행동서술 짧게 ((담배를 비벼 끈다.)) (3) 한 호흡으로 풀어내는 길이.',
    '',
  ];

  examples.forEach((ex, i) => {
    lines.push(`[예시 ${i + 1} — ${ex.trigger}]`);
    lines.push(`현재 상태: [감정: ${ex.state.emotion}] [관계: ${ex.state.relation}] [최근 사건: ${ex.state.recent}]`);
    lines.push(`행님: ${ex.user}`);
    lines.push(`조폭 동생: ${ex.bot}`);
    lines.push('');
  });

  return lines.join('\n');
}

